import { copyFile, mkdir, readdir, stat, writeFile } from "node:fs/promises"
import { basename, extname, join, relative, resolve, sep } from "node:path"
import { WorkspacePolicy } from "../security/workspace.js"

const MAX_INGEST_BYTES = 512 * 1024
const IGNORED_DIRECTORIES = new Set([".git", "node_modules", ".ag2cli"])

export interface WikiStatus {
  readonly root: string
  readonly initialized: boolean
  readonly pages: readonly string[]
}

export interface WikiStore {
  init(): Promise<string>
  status(): Promise<string>
  scan(): Promise<string>
  ingest(path: string): Promise<string>
}

export function createWikiStore(workspaceRoot: string, wikiRoot: string): WikiStore {
  const root = resolve(workspaceRoot, wikiRoot)
  assertInside(workspaceRoot, root, "Wiki root")
  const workspace = new WorkspacePolicy({ workspaceRoot })
  return {
    async init() {
      const safeRoot = await workspace.resolveWithin(root, "write")
      await mkdir(safeRoot, { recursive: true })
      const index = await workspace.resolveWithin(join(safeRoot, "README.md"), "write")
      try {
        await stat(index)
      } catch {
        await writeFile(index, "# Project Wiki\n\nGenerated and maintained by `ag2cli /wiki scan`.\n", "utf8")
      }
      return `Wiki initialized: ${displayPath(workspaceRoot, root)}`
    },
    async status() {
      const safeRoot = await workspace.resolveWithin(root, "traverse")
      const result = await collectPages(safeRoot)
      return [
        "Wiki",
        `  root: ${displayPath(workspaceRoot, root)}`,
        `  pages: ${result.length}`,
        ...result.map((page) => `  - ${page}`),
      ].join("\n")
    },
    async scan() {
      const safeRoot = await workspace.resolveWithin(root, "write")
      await mkdir(safeRoot, { recursive: true })
      const files = await collectProjectFiles(workspaceRoot)
      const content = [
        "# Codebase Overview",
        "",
        "This page is generated by `ag2cli /wiki scan`.",
        "",
        "## Files",
        ...files.map((file) => `- \`${file}\``),
        "",
      ].join("\n")
      const output = await workspace.resolveWithin(join(safeRoot, "codebase.md"), "write")
      await writeFile(output, content, "utf8")
      return `Wiki scan complete: ${files.length} files`
    },
    async ingest(path) {
      const source = await workspace.resolveWithin(resolve(workspaceRoot, path), "read")
      if (source.split(sep).some((part) => part === ".git" || part === "node_modules" || part === ".env" || part.startsWith(".env."))) {
        throw new Error("Wiki ingest does not allow sensitive or dependency directories")
      }
      const sourceStat = await stat(source)
      if (!sourceStat.isFile()) throw new Error("Wiki ingest accepts files only")
      if (sourceStat.size > MAX_INGEST_BYTES) throw new Error(`Input file exceeds the ${MAX_INGEST_BYTES}-byte limit`)
      const extension = extname(source).toLowerCase()
      if (![".md", ".txt", ".json", ".ts", ".tsx", ".js", ".jsx"].includes(extension)) {
        throw new Error("Wiki ingest accepts text files only")
      }
      const safeRoot = await workspace.resolveWithin(root, "write")
      await mkdir(safeRoot, { recursive: true })
      const target = await workspace.resolveWithin(join(safeRoot, basename(source).replace(/[^a-zA-Z0-9._-]/g, "-")), "write")
      await copyFile(source, target)
      return `Imported into the Wiki: ${displayPath(workspaceRoot, target)}`
    },
  }
}

function assertInside(workspaceRoot: string, target: string, label: string): void {
  const root = resolve(workspaceRoot)
  const candidate = resolve(target)
  if (candidate !== root && !candidate.startsWith(`${root}${sep}`)) throw new Error(`${label} must be inside the current workspace`)
}

async function collectPages(root: string): Promise<string[]> {
  try {
    return (await readdir(root, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
      .map((entry) => entry.name)
      .sort()
  } catch {
    return []
  }
}

async function collectProjectFiles(root: string, directory = root): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true })
  const files: string[] = []
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.isSymbolicLink() || (entry.isDirectory() && IGNORED_DIRECTORIES.has(entry.name))) continue
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...(await collectProjectFiles(root, path)))
    else if (entry.isFile()) files.push(relative(root, path))
    if (files.length >= 2_000) return files.slice(0, 2_000)
  }
  return files
}

function displayPath(workspaceRoot: string, path: string): string {
  const value = relative(workspaceRoot, path)
  return value.length === 0 ? "." : value
}
